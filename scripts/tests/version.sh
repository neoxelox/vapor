#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SOURCE_SCRIPT="$ROOT_DIR/scripts/version.sh"

# These tests build isolated fixture repos via `git init`. When the test runs
# inside a parent `git` operation (e.g. the project's pre-commit hook), git
# exports GIT_DIR / GIT_WORK_TREE / GIT_INDEX_FILE / etc. into the hook's
# environment. Those override `git -C "$repo"` and cause `git init` to
# "re-init" the parent repo instead of the temp dir, which breaks every
# fixture-based assertion. Drop them so child `git` invocations resolve
# their repo from the cwd / -C path like a fresh shell would.
# Git has the list of those variables; the names after it are for a
# git that has none.
# shellcheck disable=SC2046
unset $(git rev-parse --local-env-vars 2>/dev/null || true) \
  GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY \
  GIT_COMMON_DIR GIT_NAMESPACE GIT_PREFIX GIT_CONFIG_PARAMETERS \
  GIT_CONFIG_COUNT

# Isolate config-driven git behavior too: a contributor's global
# `commit.gpgsign = true` (without a usable key) or a `core.hooksPath`
# that rejects these commits would fail every fixture commit, and thus
# the required `./scripts/test.sh` gate, for reasons unrelated to the
# code under test. (git >= 2.32 honors these overrides.)
export GIT_CONFIG_GLOBAL=/dev/null
export GIT_CONFIG_SYSTEM=/dev/null

export GIT_AUTHOR_NAME="Vapor Test"
export GIT_AUTHOR_EMAIL="vapor-tests@example.com"
export GIT_COMMITTER_NAME="$GIT_AUTHOR_NAME"
export GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"

TEMP_REPOS=()

cleanup() {
  local repo
  for repo in "${TEMP_REPOS[@]:-}"; do
    rm -rf "$repo"
  done
}

trap cleanup EXIT

fail() {
  printf '[version-test] %s\n' "$1" >&2
  exit 1
}

assert_equals() {
  local actual="$1"
  local expected="$2"
  local context="$3"

  if [[ "$actual" != "$expected" ]]; then
    fail "$context: expected '$expected' but got '$actual'"
  fi
}

assert_contains() {
  local haystack="$1"
  local needle="$2"
  local context="$3"

  if [[ "$haystack" != *"$needle"* ]]; then
    fail "$context: missing '$needle'"
  fi
}

make_repo() {
  local version="$1"
  local repo

  repo="$(mktemp -d)"
  TEMP_REPOS+=("$repo")

  mkdir -p "$repo/scripts"
  cp "$SOURCE_SCRIPT" "$repo/scripts/version.sh"
  chmod +x "$repo/scripts/version.sh"

  cat > "$repo/VERSION" <<EOF
$version
EOF

  cat > "$repo/Cargo.toml" <<EOF
[workspace]
members = []
resolver = "2"

[workspace.package]
version = "$version"
EOF

  cat > "$repo/CHANGELOG.md" <<'EOF'
# Changelog

## [Unreleased]
EOF

  git -C "$repo" init -b main >/dev/null
  git -C "$repo" add VERSION Cargo.toml CHANGELOG.md scripts/version.sh
  git -C "$repo" commit -m "chore: seed version test fixture" >/dev/null

  printf '%s\n' "$repo"
}

# A fixture with one member crate and a lockfile, so the lockfile
# checks have something to read. The crate has no dependency, so cargo
# never needs the network.
make_repo_with_member() {
  local version="$1"
  local repo

  repo="$(make_repo "$version")"

  cat > "$repo/Cargo.toml" <<EOF
[workspace]
members = ["crates/demo"]
resolver = "2"

[workspace.package]
version = "$version"
EOF

  mkdir -p "$repo/crates/demo/src"
  cat > "$repo/crates/demo/Cargo.toml" <<'EOF'
[package]
name = "vapor-demo"
version.workspace = true
edition = "2021"
EOF
  : > "$repo/crates/demo/src/lib.rs"

  cat > "$repo/Cargo.lock" <<EOF
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "vapor-demo"
version = "$version"
EOF

  git -C "$repo" add Cargo.toml Cargo.lock crates
  git -C "$repo" commit -m "chore: add a member crate" >/dev/null

  printf '%s\n' "$repo"
}

lock_version() {
  python3 - "$1/Cargo.lock" <<'PY'
from pathlib import Path
import sys

lines = Path(sys.argv[1]).read_text(encoding="utf-8").splitlines()
for index, line in enumerate(lines):
    if line.strip() == 'name = "vapor-demo"':
        print(lines[index + 1].split("=", 1)[1].strip().strip('"'))
        break
PY
}

# Runs a version.sh command that must fail, and checks the message and
# that VERSION did not move.
assert_refused() {
  local repo="$1" needle="$2" context="$3" before output
  shift 3
  before="$(tr -d '[:space:]' < "$repo/VERSION")"

  if output="$(cd "$repo" && ./scripts/version.sh "$@" 2>&1)"; then
    fail "$context: the command unexpectedly succeeded"
  fi

  assert_contains "$output" "$needle" "$context"
  assert_equals "$(tr -d '[:space:]' < "$repo/VERSION")" "$before" "$context VERSION"
}

write_changelog_entry() {
  local repo="$1"
  local version="$2"

  cat > "$repo/CHANGELOG.md" <<EOF
# Changelog

## [Unreleased]

## [$version] - 2026-03-10

- Release preparation.
EOF
}

cargo_version() {
  python3 - "$1/Cargo.toml" <<'PY'
from pathlib import Path
import sys

path = Path(sys.argv[1])
for line in path.read_text(encoding="utf-8").splitlines():
    stripped = line.strip()
    if stripped.startswith("version = "):
        print(stripped.split("=", 1)[1].strip().strip('"'))
        break
PY
}

test_rejects_dirty_worktree_except_changelog() {
  local repo output version
  repo="$(make_repo "0.1.0")"
  write_changelog_entry "$repo" "0.2.0"
  printf 'extra\n' > "$repo/notes.txt"

  if output="$(cd "$repo" && ./scripts/version.sh set 0.2.0 2>&1)"; then
    fail "dirty worktree release unexpectedly succeeded"
  fi

  assert_contains "$output" "clean worktree except CHANGELOG.md" "dirty worktree error"
  version="$(tr -d '[:space:]' < "$repo/VERSION")"
  assert_equals "$version" "0.1.0" "dirty worktree VERSION"
}

test_requires_matching_changelog_entry() {
  local repo output version
  repo="$(make_repo "0.1.0")"

  if output="$(cd "$repo" && ./scripts/version.sh set 0.2.0 2>&1)"; then
    fail "release without changelog entry unexpectedly succeeded"
  fi

  assert_contains "$output" "CHANGELOG.md missing section for [0.2.0]" "changelog gate"
  version="$(tr -d '[:space:]' < "$repo/VERSION")"
  assert_equals "$version" "0.1.0" "missing changelog VERSION"
}

test_set_creates_release_commit_and_tag() {
  local repo output version subject tag status
  repo="$(make_repo "0.1.0")"
  write_changelog_entry "$repo" "0.2.0"

  output="$(cd "$repo" && ./scripts/version.sh set 0.2.0)"

  version="$(tr -d '[:space:]' < "$repo/VERSION")"
  assert_equals "$version" "0.2.0" "stable set VERSION"
  assert_equals "$(cargo_version "$repo")" "0.2.0" "stable set Cargo.toml"

  subject="$(git -C "$repo" log -1 --format=%s)"
  assert_equals "$subject" "release: v0.2.0" "stable set commit subject"

  tag="$(git -C "$repo" tag --list "v0.2.0")"
  assert_equals "$tag" "v0.2.0" "stable set tag"

  status="$(git -C "$repo" status --short)"
  assert_equals "$status" "" "stable set worktree"
  assert_contains "$output" "git push origin \"main\" --follow-tags" "stable set push command"
}

test_prerelease_command_moves_along_the_current_prerelease() {
  local repo version tag
  repo="$(make_repo "0.2.0-beta.2")"
  write_changelog_entry "$repo" "0.2.0-beta.3"

  (cd "$repo" && ./scripts/version.sh prerelease beta >/dev/null)

  version="$(tr -d '[:space:]' < "$repo/VERSION")"
  assert_equals "$version" "0.2.0-beta.3" "prerelease VERSION"
  assert_equals "$(cargo_version "$repo")" "0.2.0-beta.3" "prerelease Cargo.toml"
  tag="$(git -C "$repo" tag --list "v0.2.0-beta.3")"
  assert_equals "$tag" "v0.2.0-beta.3" "prerelease tag"

  # A later track starts at 1.
  write_changelog_entry "$repo" "0.2.0-rc.1"
  (cd "$repo" && ./scripts/version.sh prerelease rc >/dev/null)
  assert_equals "$(tr -d '[:space:]' < "$repo/VERSION")" "0.2.0-rc.1" "next track VERSION"
}

test_refuses_a_version_that_sorts_lower() {
  local repo

  # A prerelease of a version that is already out sorts below it.
  repo="$(make_repo "0.2.0")"
  write_changelog_entry "$repo" "0.2.0-rc.1"
  assert_refused "$repo" "is stable" "prerelease on a stable version" prerelease rc
  assert_refused "$repo" "sorts below the current" "set to a prerelease of the current version" set 0.2.0-rc.1
  write_changelog_entry "$repo" "0.1.9"
  assert_refused "$repo" "sorts below the current" "set to a lower version" set 0.1.9

  # An earlier track of the same base sorts below a later one.
  repo="$(make_repo "0.2.0-beta.1")"
  write_changelog_entry "$repo" "0.2.0-alpha.2"
  assert_refused "$repo" "sorts below the current" "back to an earlier track" prerelease alpha 2
  write_changelog_entry "$repo" "0.2.0-beta.1"
  assert_refused "$repo" "VERSION is already" "same version" set 0.2.0-beta.1
}

test_refuses_a_number_with_a_leading_zero() {
  local repo
  repo="$(make_repo "0.2.0-rc.7")"
  write_changelog_entry "$repo" "0.2.0-rc.08"

  assert_refused "$repo" "invalid version '0.2.0-rc.08'" "leading zero in set" set 0.2.0-rc.08
  assert_refused "$repo" "no leading zero" "leading zero in prerelease" prerelease rc 08
  assert_refused "$repo" "invalid version '0.02.0'" "leading zero in the base" set 0.02.0
}

test_bump_moves_a_stable_version() {
  local repo
  repo="$(make_repo "0.1.4")"

  write_changelog_entry "$repo" "0.1.5"
  (cd "$repo" && ./scripts/version.sh bump patch >/dev/null)
  assert_equals "$(tr -d '[:space:]' < "$repo/VERSION")" "0.1.5" "bump patch"

  write_changelog_entry "$repo" "0.2.0"
  (cd "$repo" && ./scripts/version.sh bump minor >/dev/null)
  assert_equals "$(tr -d '[:space:]' < "$repo/VERSION")" "0.2.0" "bump minor"

  write_changelog_entry "$repo" "1.0.0"
  (cd "$repo" && ./scripts/version.sh bump major >/dev/null)
  assert_equals "$(tr -d '[:space:]' < "$repo/VERSION")" "1.0.0" "bump major"
  assert_equals "$(git -C "$repo" tag --list "v1.0.0")" "v1.0.0" "bump major tag"

  assert_refused "$repo" "unsupported bump segment" "unknown segment" bump build
}

test_bump_refuses_a_prerelease() {
  local repo
  repo="$(make_repo "0.2.0-alpha.3")"
  write_changelog_entry "$repo" "0.2.1"

  # 0.2.1 from 0.2.0-alpha.3 would leave 0.2.0 unreleased.
  assert_refused "$repo" "would skip 0.2.0" "bump on a prerelease" bump patch
}

test_refuses_an_existing_tag_and_another_branch() {
  local repo
  repo="$(make_repo "0.1.0")"
  write_changelog_entry "$repo" "0.2.0"
  git -C "$repo" tag v0.2.0

  assert_refused "$repo" "tag 'v0.2.0' already exists" "existing tag" set 0.2.0

  git -C "$repo" tag -d v0.2.0 >/dev/null
  git -C "$repo" checkout -q -b topic
  assert_refused "$repo" "must run from 'main'" "another branch" set 0.2.0
}

test_metadata_maps_each_track_to_an_apple_build_version() {
  local repo output
  local cases=("0.2.0-alpha.3:0.2.0a3:true" "0.2.0-beta.12:0.2.0b12:true" "0.2.0-rc.1:0.2.0fc1:true" "1.4.2:1.4.2:false")
  local entry version build prerelease

  for entry in "${cases[@]}"; do
    IFS=: read -r version build prerelease <<< "$entry"
    repo="$(make_repo "$version")"
    output="$(cd "$repo" && ./scripts/version.sh metadata)"

    assert_contains "$output" "VAPOR_VERSION=$version" "metadata version for $version"
    assert_contains "$output" "VAPOR_VERSION_TAG=v$version" "metadata tag for $version"
    assert_contains "$output" "VAPOR_RELEASE_VERSION=${version%%-*}" "metadata base for $version"
    assert_contains "$output" "VAPOR_APPLE_BUILD_VERSION=$build" "metadata build for $version"
    assert_contains "$output" "VAPOR_VERSION_IS_PRERELEASE=$prerelease" "metadata prerelease flag for $version"
  done
}

test_check_sync_reports_each_mismatch() {
  local repo output
  repo="$(make_repo_with_member "0.1.0")"

  (cd "$repo" && ./scripts/version.sh check-sync) || fail "check-sync failed on a fixture in sync"

  # The lockfile behind VERSION.
  sed -i.bak 's/^version = "0.1.0"$/version = "0.0.9"/' "$repo/Cargo.lock"
  if output="$(cd "$repo" && ./scripts/version.sh check-sync 2>&1)"; then
    fail "check-sync passed with a stale lockfile"
  fi
  assert_contains "$output" "Cargo.lock do not match VERSION 0.1.0: vapor-demo=0.0.9" "stale lockfile"
  mv "$repo/Cargo.lock.bak" "$repo/Cargo.lock"

  # The manifest behind VERSION.
  printf '0.3.0\n' > "$repo/VERSION"
  if output="$(cd "$repo" && ./scripts/version.sh check-sync 2>&1)"; then
    fail "check-sync passed with a stale manifest"
  fi
  assert_contains "$output" "Cargo.toml version '0.1.0' does not match VERSION '0.3.0'" "stale manifest"

  # sync brings the manifest and the lockfile to VERSION.
  output="$(cd "$repo" && CARGO_NET_OFFLINE=true ./scripts/version.sh sync)"
  assert_equals "$output" "0.3.0" "sync output"
  assert_equals "$(cargo_version "$repo")" "0.3.0" "sync Cargo.toml"
  assert_equals "$(lock_version "$repo")" "0.3.0" "sync Cargo.lock"
  (cd "$repo" && ./scripts/version.sh check-sync) || fail "check-sync failed after sync"
}

test_set_commits_the_lockfile() {
  local repo
  repo="$(make_repo_with_member "0.1.0")"
  write_changelog_entry "$repo" "0.2.0"

  (cd "$repo" && CARGO_NET_OFFLINE=true ./scripts/version.sh set 0.2.0 >/dev/null)

  assert_equals "$(lock_version "$repo")" "0.2.0" "set Cargo.lock"
  assert_equals "$(git -C "$repo" status --short)" "" "set worktree with a lockfile"
  assert_contains "$(git -C "$repo" show --stat --format= HEAD)" "Cargo.lock" "lockfile in the release commit"
}

test_release_command_strips_prerelease_and_tags_stable() {
  local repo version subject tag
  repo="$(make_repo "0.2.0-rc.1")"
  write_changelog_entry "$repo" "0.2.0"

  cd "$repo"
  ./scripts/version.sh release >/dev/null
  cd "$ROOT_DIR"

  version="$(tr -d '[:space:]' < "$repo/VERSION")"
  assert_equals "$version" "0.2.0" "release VERSION"
  subject="$(git -C "$repo" log -1 --format=%s)"
  assert_equals "$subject" "release: v0.2.0" "release commit subject"
  tag="$(git -C "$repo" tag --list "v0.2.0")"
  assert_equals "$tag" "v0.2.0" "release tag"
}

